class TreeNode:
    def __init__(self, id, left=None, right=None, distance=0.0, size=1, label=None):
        """
        Represents a node in the hierarchical clustering tree.
        :param id: The ID of the cluster or data point.
        :param left: Left child node (TreeNode or None).
        :param right: Right child node (TreeNode or None).
        :param distance: Distance at which this node was created.
        :param size: Number of original data points in this cluster.
        """
        self.id = id
        self.left = left
        self.right = right
        self.distance = distance
        self.size = size
        self.label = label

    def __repr__(self):
        """String representation of the tree node."""
        return f"<{self.label}, {self.distance}>"

def linkage_to_tree(linkage_matrix, names):
    """
    Converts a linkage matrix into a tree structure with labeled leaf nodes.
    :param linkage_matrix: Linkage matrix from scipy.cluster.hierarchy.linkage.
    :param names: List of names corresponding to the original data points.
    :return: Root node of the tree.
    """
    n = linkage_matrix.shape[0] + 1  # Number of original data points
    nodes = {i: TreeNode(id=i, label=names[i]) for i in range(n)}  # Create initial leaf nodes with labels

    for i, (cluster1, cluster2, distance, count) in enumerate(linkage_matrix):
        cluster1, cluster2 = int(cluster1), int(cluster2)  # Convert to integer indices
        new_node = TreeNode(
            id=n + i,  # Assign a unique ID for the new cluster
            left=nodes[cluster1],  # Left child
            right=nodes[cluster2],  # Right child
            distance=distance,
            size=int(count),  # Number of points in the cluster
            label=names[i]
        )
        nodes[n + i] = new_node  # Add the new cluster node

    return nodes[max(nodes.keys())]  # Return the root node

